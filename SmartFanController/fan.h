#pragma once
/*
 * ============================================================================
 *   ماژول کنترل فن
 * ============================================================================
 *   این ماژول کنترل سرعت فن را بر اساس نوع فن فعال (دو سیمه یا چهار سیمه)
 *   انجام می‌دهد:
 *     • فن دو سیمه  : خروجی PWM روی FAN_PWM_PIN که درایور MOSFET را کنترل می‌کند
 *     • فن چهار سیمه: خروجی PWM با فرکانس ~۲۵kHz روی تایمر ۱ + خواندن RPM
 *                      از سیم تاخ (در صورت فعال بودن)
 * ============================================================================
 */

#include <Arduino.h>
#include "config.h"

// مقداردهی اولیه پایه‌ها و تایمرها. در setup() صدا زده می‌شود.
void fanBegin();

// تعیین سرعت هدف فن بر حسب درصد (۰ تا ۱۰۰).
// این مقدار صرفاً «هدف» است؛ اعمال واقعی در fanUpdate انجام می‌شود.
void fanSetTargetDutyPercent(float dutyPercent);

// به‌روزرسانی خروجی PWM و خواندن RPM.
// این تابع باید دوره‌ای (مثلاً هر ۱۰۰ میلی‌ثانیه) صدا زده شود.
void fanUpdate(uint32_t nowMs);

// سرعت فعلی (اعمال‌شده) فن بر حسب درصد
float fanGetCurrentDutyPercent();

// ورود به حالت ایمن: فن بی‌درنگ با سرعت کامل کار می‌کند.
void fanEnterFailsafe();

// خروج از حالت ایمن و بازگشت به کنترل خودکار.
void fanExitFailsafe();

// آیا فن در حالت ایمن است؟
bool fanIsInFailsafe();

// سرعت چرخش فن (RPM) برای فن چهار سیمه؛ برای فن دو سیمه همیشه صفر.
uint16_t fanGetRpm();
