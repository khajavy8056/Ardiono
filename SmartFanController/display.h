#pragma once
/*
 * ============================================================================
 *   ماژول نمایشگر
 * ============================================================================
 *   نمایش دما، رطوبت (در صورت وجود)، درصد سرعت فن و RPM (برای فن چهار سیمه).
 *   نوع نمایشگر از config.h خوانده می‌شود؛ اگر DISPLAY_NONE باشد، همه
 *   توابع این ماژول بدون هیچ عملیاتی می‌شوند و کتابخانه‌ای هم لازم نیست.
 * ============================================================================
 */

#include <Arduino.h>
#include "config.h"

// داده‌هایی که نمایشگر باید نشان دهد
struct DisplayData
{
  float   temperatureC;   // دمای فعلی (سلسیوس)
  float   humidity;       // رطوبت (درصد) — فقط برای DHT
  float   dutyPercent;    // درصد سرعت فن
  uint16_t rpm;           // سرعت چرخش فن (فقط فن چهار سیمه)
  bool    sensorOk;       // آیا سنسور داده معتبر می‌دهد؟
  bool    failsafe;       // آیا فن در حالت ایمن است؟
};

// مقداردهی اولیه نمایشگر. در setup() صدا زده می‌شود.
void displayBegin();

// به‌روزرسانی محتوای نمایشگر.
// زمان‌بندی فراخوانی بر عهده ماژول controller است.
void displayUpdate(const DisplayData &data);
